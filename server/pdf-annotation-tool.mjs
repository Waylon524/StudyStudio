import {checkedPdfAnnotation,PDF_MARKUP_COLORS,boundPdfRegion} from '../shared/pdf-markup.mjs';

const MAX_TURN_ANNOTATIONS=24,MAX_TOOL_CALLS=64;
const scalar={type:'number',minimum:0,maximum:1};
const annotationProperties={
  kind:{type:'string',enum:['text','line','rectangle','ellipse']},x:scalar,y:scalar,endX:scalar,endY:scalar,
  color:{type:'string',enum:PDF_MARKUP_COLORS},text:{type:'string',maxLength:1000},
  fontSize:{type:'number',minimum:8,maximum:48},strokeWidth:{type:'number',minimum:1,maximum:8}
};
export const pdfAnnotationTool={
  name:'study_pdf_annotate',
  description:'在当前课程 PDF 上新增一条教学批注，和用户批注共用保存与显示。省略 sourceId/page 使用本轮固定课件页；显式目标必须已在本轮读过。annotation 为 text/line/rectangle/ellipse，不提供 id。坐标为显示页面左上角起的 [0,1] 比例；任意坐标须先读取该页图像。省略全部坐标可直接圈画本轮用户选区（line 为选区底部下划线），text 在选区起点或固定页角落放置短注释。默认红色、16号字、2px线宽。仅新增，不修改或删除已有批注，单轮最多24条；成功后再告知用户已保存。',
  inputSchema:{type:'object',properties:{sourceId:{type:'string',pattern:'^[0-9a-f]{24}$'},page:{type:'integer',minimum:1},annotation:{type:'object',properties:annotationProperties,required:['kind'],additionalProperties:false}},required:['annotation'],additionalProperties:false}
};
const record=value=>value!==null&&typeof value==='object'&&!Array.isArray(value);
const allowedKeys=new Set(Object.keys(annotationProperties));

/** Resolve against this turn, never against the user's later reader navigation. */
function prepare(active,args){
  if(!record(args)||Object.keys(args).some(key=>!['sourceId','page','annotation'].includes(key)))throw new TypeError('PDF 批注参数无效。');
  const fixed=active.readerSnapshot,explicit=args.sourceId!==undefined||args.page!==undefined;
  const sourceId=explicit?args.sourceId:fixed?.sourceId,page=explicit?args.page:fixed?.page;
  if(typeof sourceId!=='string'||!/^[0-9a-f]{24}$/.test(sourceId)||!Number.isSafeInteger(page)||page<1)throw new TypeError('请先打开 PDF，或指定已在本轮读取的课程 PDF 与页码。');
  const sameFixed=fixed?.sourceId===sourceId&&fixed.page===page;
  const evidence=active.readEvidence?.get(`${sourceId}:${page}`);
  if(!sameFixed&&!evidence)throw new TypeError('请先在本轮读取指定的课程 PDF 页面，再添加批注。');
  const input=args.annotation;
  if(!record(input)||Object.keys(input).some(key=>!allowedKeys.has(key)))throw new TypeError('请只提供新批注的种类、位置和样式，不提供已有批注编号。');
  const hasCoordinates=['x','y','endX','endY'].some(key=>input[key]!==undefined);
  const region=sameFixed?boundPdfRegion(active.selectedRegion):null;
  let annotation={...input};
  if(hasCoordinates){
    if(!evidence?.imageAvailable)throw new TypeError('任意位置批注前，请先读取并查看这页 PDF 的图像；仅有页码或选中文字不能确定位置。');
  }else if(region){
    annotation={...annotation,x:region.x,y:region.y};
    if(input.kind==='line')annotation={...annotation,y:region.y+region.height,endX:region.x+region.width,endY:region.y+region.height};
    else if(input.kind!=='text')annotation={...annotation,endX:region.x+region.width,endY:region.y+region.height};
  }else if(input.kind==='text')annotation={...annotation,x:.04,y:.04};
  else throw new TypeError('圈画前请框选目标，或先读取页面图像并提供准确的位置。');
  if(input.kind==='text'){
    if(typeof input.text!=='string'||!input.text.trim()||input.text.length>1000)throw new TypeError('教学文字批注应为1至1000个字符。');
    if(input.fontSize!==undefined&&(!Number.isFinite(input.fontSize)||input.fontSize<8||input.fontSize>48))throw new TypeError('教学批注字号应在8至48之间。');
    annotation.fontSize ??= 16;
  }else{
    if(input.strokeWidth!==undefined&&(!Number.isFinite(input.strokeWidth)||input.strokeWidth<1||input.strokeWidth>8))throw new TypeError('教学批注线宽应在1至8之间。');
    annotation.strokeWidth ??= 2;
  }
  annotation.color ??= 'red';
  // The real identifier is generated by persistence; this validates the common shape first.
  const checked=checkedPdfAnnotation({...annotation,id:'00000000-0000-4000-8000-000000000000'});
  const {id,...value}=checked;
  return {sourceId,page,annotation:value};
}

export async function annotatePdf({pdfAnnotations,course,active,args,threadId,turnId,callId,write,onUpdate,isActive}){
  if(!active||active.course?.id!==course.id||!isActive())throw new Error('本轮对话已经结束，未添加 PDF 批注。');
  if(typeof callId!=='string'||!callId||callId.length>200)throw new TypeError('批注工具调用编号无效。');
  const request=prepare(active,args);
  active.pdfAnnotationCalls ||= new Map();
  if(active.pdfAnnotationCalls.has(callId))return active.pdfAnnotationCalls.get(callId);
  if(active.pdfAnnotationCalls.size>=MAX_TOOL_CALLS)throw new TypeError('本轮批注调用次数已达到上限。');
  if((active.pdfAnnotationCount||0)>=MAX_TURN_ANNOTATIONS)throw new TypeError('本轮最多添加24条教学批注，请先完成当前讲解。');
  active.pdfAnnotationCount=(active.pdfAnnotationCount||0)+1;
  const task=Promise.resolve().then(()=>write(async()=>{
    if(!isActive())throw new Error('本轮对话已经结束，未添加 PDF 批注。');
    const result=await pdfAnnotations.create(course,request,{kind:'agent',threadId,turnId:active.turnId||turnId||null,callId});
    const scope={courseId:course.id,sourceId:request.sourceId,page:request.page};
    try{onUpdate(scope)}catch{/* Saving succeeded even if an SSE subscriber has disconnected. */}
    return {...result,...scope,coordinateSystem:'displayed_pdf_page_fraction_top_left'};
  })).catch(error=>{active.pdfAnnotationCount--;throw error});
  active.pdfAnnotationCalls.set(callId,task);
  return task;
}
