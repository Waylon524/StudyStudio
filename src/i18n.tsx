export const MESSAGES: Record<Locale, Record<MessageKey, string>> = {
  'zh-CN': zhCN,
  en,
}

const STANDARD_FOLDER_KEYS: Record<string, MessageKey> = {
  '课件': 'folder.课件',
  '教材': 'folder.教材',
  '作业': 'folder.作业',
  '笔记': 'folder.笔记',
  '课程说明': 'folder.课程说明',
  '图片': 'folder.图片',
  '其他资料': 'folder.其他资料',
  '待整理': 'folder.待整理',
  '互动页面': 'folder.互动页面',
}

let activeLocale: Locale = (() => {
  try {
    return detectInitialLocale(
      typeof localStorage !== 'undefined' ? localStorage.getItem(LOCALE_STORAGE_KEY) : null,
      typeof navigator !== 'undefined' ? navigator.language : null
    )
  } catch {
    return DEFAULT_LOCALE
  }
})()

export function getCurrentLocale(): Locale {
  return activeLocale
}

export function translate(locale: Locale, key: MessageKey, params?: Record<string, string | number>): string {
  const table = MESSAGES[locale] || MESSAGES[DEFAULT_LOCALE]
  let text = table[key] ?? MESSAGES[DEFAULT_LOCALE][key] ?? key
  if (params) {
    text = text.replace(/\{(\w+)\}/g, (_, name: string) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : `{${name}}`
    )
  }
  return text
}

export function tCurrent(key: MessageKey, params?: Record<string, string | number>): string {
  return translate(activeLocale, key, params)
}

export type I18nContextValue = {
  locale: Locale
  setLocale: (next: Locale) => void
  syncLocaleFromServer: (serverLocale: unknown) => void
  t: (key: MessageKey, params?: Record<string, string | number>) => string
  collator: Intl.Collator
  courseDisplayName: (course?: { id: string; name: string } | null) => string
  folderDisplayName: (path: string) => string
  questionTypeLabel: (type?: string) => string
  formatDateTime: (iso: string, opts?: Intl.DateTimeFormatOptions) => string
  formatCalendarDate: (yyyyMmDd: string) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => activeLocale)

  useEffect(() => {
    activeLocale = locale
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, locale)
    } catch {}
    if (typeof document !== 'undefined') {
      document.documentElement.lang = locale
      document.title = translate(locale, 'app.title')
    }
  }, [locale])

  const setLocale = useCallback((next: Locale) => {
    const normalized = normalizeLocale(next, DEFAULT_LOCALE)
    activeLocale = normalized
    setLocaleState(normalized)
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, normalized)
    } catch {}
    void fetch('/api/settings/locale', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ locale: normalized }),
    }).catch(() => {})
  }, [])

  const syncLocaleFromServer = useCallback((serverLocale: unknown) => {
    if (!isValidLocale(serverLocale)) return
    let stored: string | null = null
    try {
      stored = localStorage.getItem(LOCALE_STORAGE_KEY)
    } catch {}
    if (!stored || !isValidLocale(stored)) {
      activeLocale = serverLocale
      setLocaleState(serverLocale)
    }
  }, [])

  const value = useMemo<I18nContextValue>(() => {
    const meta = LOCALE_META[locale] || LOCALE_META[DEFAULT_LOCALE]
    const collator = new Intl.Collator(meta.collator, { numeric: true, sensitivity: 'base' })
    const t = (key: MessageKey, params?: Record<string, string | number>) => translate(locale, key, params)

    const courseDisplayName = (course?: { id: string; name: string } | null) => {
      if (!course) return t('course.general')
      if (course.id === 'general' && course.name === '通用学习') return t('course.general')
      return course.name
    }

    const folderDisplayName = (folderPath: string) => {
      if (!folderPath) return t('folder.uncategorized')
      return folderPath
        .split('/')
        .map(segment => {
          const key = STANDARD_FOLDER_KEYS[segment]
          return key ? t(key) : segment
        })
        .join(' / ')
    }

    const questionTypeLabel = (type?: string) => {
      const map: Record<StudyType, MessageKey> = {
        choice: 'practice.type.choice',
        true_false: 'practice.type.true_false',
        fill_blank: 'practice.type.fill_blank',
        short_answer: 'practice.type.short_answer',
        flashcard: 'practice.type.flashcard',
      }
      const key = type && Object.prototype.hasOwnProperty.call(map, type) ? map[type as StudyType] : 'practice.type.default'
      return t(key)
    }

    const formatDateTime = (iso: string, opts?: Intl.DateTimeFormatOptions) => {
      if (!iso || Number.isNaN(Date.parse(iso))) return ''
      try {
        return new Date(iso).toLocaleString(meta.collator, opts)
      } catch {
        return iso
      }
    }

    const formatCalendarDate = (yyyyMmDd: string) => {
      const parts = yyyyMmDd.split('-').map(Number)
      if (parts.length !== 3 || parts.some(n => !Number.isFinite(n))) return yyyyMmDd
      const [year, month, day] = parts
      if (locale === 'zh-CN') return `${year} 年 ${month} 月 ${day} 日`
      try {
        return new Intl.DateTimeFormat('en-US', { year: 'numeric', month: 'short', day: 'numeric', timeZone: 'UTC' }).format(
          new Date(Date.UTC(year, month - 1, day))
        )
      } catch {
        return yyyyMmDd
      }
    }

    return {
      locale,
      setLocale,
      syncLocaleFromServer,
      t,
      collator,
      courseDisplayName,
      folderDisplayName,
      questionTypeLabel,
      formatDateTime,
      formatCalendarDate,
    }
  }, [locale, setLocale, syncLocaleFromServer])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext)
  if (!ctx) {
    throw new Error('useI18n must be used inside <I18nProvider>')
  }
  return ctx
}
